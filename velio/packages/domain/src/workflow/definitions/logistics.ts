import type { WorkflowDefinition } from '../types';
import { autoCloseTransition, cancellationTransitions, reviewTransition } from './common';

/**
 * Leva e traz: retirar o bem do cliente, levar a um destino (lavagem, oficina, lavanderia),
 * aguardar a execução por terceiro, coletar de novo e devolver. Cada posse muda com custódia.
 */
export const logisticsWorkflow: WorkflowDefinition = {
  kind: 'LOGISTICS',
  version: 1,
  initial: 'REQUESTED',
  states: {
    REQUESTED: { slaSeconds: 60 },
    MATCHING: { slaSeconds: 1800 },
    OFFERED: { slaSeconds: 1800 },
    DRIVER_ASSIGNED: { slaSeconds: 1800, providerBusy: true },
    EN_ROUTE_PICKUP: { providerBusy: true, liveLocation: true },
    PICKED_UP: { providerBusy: true, liveLocation: true },
    IN_TRANSIT: { providerBusy: true, liveLocation: true },
    AT_DESTINATION: { providerBusy: true },
    THIRD_PARTY_IN_PROGRESS: {},
    THIRD_PARTY_DONE: { slaSeconds: 3600 },
    RETURN_PICKUP: { providerBusy: true, liveLocation: true },
    RETURNING: { providerBusy: true, liveLocation: true },
    DELIVERED: { providerBusy: true },
    COMPLETED: {},
    REVIEWED: { terminal: true },
    CLOSED: { terminal: true },
    NO_PROVIDER_FOUND: { slaSeconds: 900 },
    CANCELLED_BY_CUSTOMER: { terminal: true },
    CANCELLED_BY_PLATFORM: { terminal: true },
    DISPUTED: {},
    REFUNDED: { terminal: true },
  },
  transitions: [
    {
      from: 'REQUESTED',
      to: 'MATCHING',
      action: 'system.start_matching',
      allowedActors: ['system'],
      effects: ['dispatch.start', 'analytics.track'],
    },
    { from: 'MATCHING', to: 'OFFERED', action: 'system.offer', allowedActors: ['system'] },
    {
      from: ['MATCHING', 'OFFERED'],
      to: 'MATCHING',
      action: 'system.wave_exhausted',
      allowedActors: ['system'],
    },
    {
      from: ['MATCHING', 'OFFERED'],
      to: 'NO_PROVIDER_FOUND',
      action: 'system.no_provider',
      allowedActors: ['system'],
      effects: ['ops.alert:no_provider'],
    },
    {
      from: ['OFFERED', 'MATCHING'],
      to: 'DRIVER_ASSIGNED',
      action: 'provider.accept',
      allowedActors: ['provider'],
      effects: [
        'dispatch.cancelOffers',
        'payments.authorize',
        'provider.setBusy',
        'notify.customer:provider_found',
        'chat.systemMessage',
        'analytics.track',
      ],
    },
    {
      from: ['NO_PROVIDER_FOUND', 'MATCHING', 'OFFERED'],
      to: 'DRIVER_ASSIGNED',
      action: 'operator.assign',
      allowedActors: ['operator'],
      effects: [
        'dispatch.cancelOffers',
        'payments.authorize',
        'provider.setBusy',
        'notify.customer:provider_found',
      ],
    },
    {
      from: 'DRIVER_ASSIGNED',
      to: 'EN_ROUTE_PICKUP',
      action: 'provider.en_route',
      allowedActors: ['provider'],
      guards: ['actorIsAssignedProvider'],
      effects: ['notify.customer:provider_en_route', 'chat.systemMessage'],
    },
    {
      from: 'EN_ROUTE_PICKUP',
      to: 'PICKED_UP',
      action: 'provider.pickup',
      allowedActors: ['provider'],
      guards: [
        'actorIsAssignedProvider',
        'requiresCustodyScan',
        'requiresVehicleHandover',
        'requiresEvidence:PICKUP',
      ],
      effects: ['custody.record', 'chat.systemMessage', 'analytics.track'],
      describe: 'Coleta com QR/placa, fotos e, para veículos, odômetro e checklist',
    },
    {
      from: 'PICKED_UP',
      to: 'IN_TRANSIT',
      action: 'provider.depart',
      allowedActors: ['provider'],
      guards: ['actorIsAssignedProvider'],
    },
    {
      from: 'IN_TRANSIT',
      to: 'AT_DESTINATION',
      action: 'provider.arrive_destination',
      allowedActors: ['provider'],
      guards: ['actorIsAssignedProvider'],
      effects: ['custody.record', 'chat.systemMessage'],
    },
    {
      from: 'AT_DESTINATION',
      to: 'THIRD_PARTY_IN_PROGRESS',
      action: 'provider.third_party_start',
      allowedActors: ['provider', 'operator'],
      guards: ['actorIsAssignedProvider'],
      effects: ['provider.setOnline', 'chat.systemMessage'],
      describe: 'Motorista fica livre enquanto o terceiro executa',
    },
    {
      from: 'THIRD_PARTY_IN_PROGRESS',
      to: 'THIRD_PARTY_DONE',
      action: 'provider.third_party_done',
      allowedActors: ['provider', 'operator', 'system'],
      effects: ['chat.systemMessage'],
    },
    {
      from: 'THIRD_PARTY_DONE',
      to: 'RETURN_PICKUP',
      action: 'provider.return_pickup',
      allowedActors: ['provider'],
      guards: ['actorIsAssignedProvider', 'requiresCustodyScan'],
      effects: ['custody.record', 'provider.setBusy', 'chat.systemMessage'],
    },
    {
      from: 'RETURN_PICKUP',
      to: 'RETURNING',
      action: 'provider.return_depart',
      allowedActors: ['provider'],
      guards: ['actorIsAssignedProvider'],
      effects: ['notify.customer:provider_en_route'],
    },
    {
      from: 'RETURNING',
      to: 'DELIVERED',
      action: 'provider.deliver',
      allowedActors: ['provider'],
      guards: [
        'actorIsAssignedProvider',
        'requiresCustodyScan',
        'requiresVehicleHandover',
        'requiresEvidence:DELIVERY',
      ],
      effects: ['custody.record', 'chat.systemMessage', 'analytics.track'],
      describe: 'Devolução com confirmação do cliente',
    },
    {
      from: 'DELIVERED',
      to: 'COMPLETED',
      action: 'provider.complete',
      allowedActors: ['provider', 'system', 'operator'],
      guards: ['noOpenAdditionalQuote'],
      effects: [
        'payments.capture',
        'wallet.settle',
        'provider.setOnline',
        'notify.customer:service_completed',
        'notify.customer:review_request',
        'analytics.track',
      ],
    },
    reviewTransition,
    autoCloseTransition,
    ...cancellationTransitions(
      ['REQUESTED', 'MATCHING', 'OFFERED', 'DRIVER_ASSIGNED', 'EN_ROUTE_PICKUP', 'NO_PROVIDER_FOUND'],
      ['DRIVER_ASSIGNED', 'EN_ROUTE_PICKUP'],
    ),
  ],
};

/** Lavanderia = logística com custódia obrigatória por saco/lacre. A API força `requiresCustody`. */
export const laundryWorkflow: WorkflowDefinition = {
  ...logisticsWorkflow,
  kind: 'LAUNDRY',
  version: 1,
};
